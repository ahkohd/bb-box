const HEADER = "<!-- Generated by scripts/reference.ts from the code. Do not edit: change the code, then run npm run reference. -->\n\n";

/** A table cell: one line, with its pipes escaped. */
function cell(text: unknown): string {
  return String(text ?? "")
    .replace(/\s*\n\s*/g, " ")
    .replace(/\|/g, "\\|")
    .replace(/(`[^`]*`)|</g, (_, code: string | undefined) => code ?? "&lt;");
}

function table(head: readonly string[], rows: readonly (readonly unknown[])[]): string {
  return [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`)].join("\n");
}

/** A heading's anchor, as GitHub makes it. */
export function anchor(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N} _-]/gu, "")
    .replace(/ /g, "-");
}

export interface Registered {
  readonly cli: { readonly name: string; readonly summary: string; readonly commands: readonly { name: string; usage: string; summary: string }[] };
  readonly tools: readonly { name: string; description: string; inputSchema: JsonSchema }[];
  readonly help: ReadonlyMap<string, string>;
}

interface JsonSchema {
  readonly type?: string | readonly string[];
  readonly description?: string;
  readonly properties?: Readonly<Record<string, JsonSchema>>;
  readonly required?: readonly string[];
  readonly enum?: readonly unknown[];
  readonly items?: JsonSchema;
  readonly anyOf?: readonly JsonSchema[];
  readonly default?: unknown;
}

/** The plugin's CLI and agent tools, as a fake BB host records them when the plugin starts. */
export async function registered(): Promise<Registered> {
  const { bb, harness } = createFakePluginHost({ pluginId: "bb-box" });
  await plugin(bb);
  const registrations = harness.inspection.registrations as unknown as { cli: Registered["cli"]; agentTools: Registered["tools"] };
  const help = new Map<string, string>();
  for (const command of registrations.cli.commands) {
    const path = command.usage.replace(/^bb box /, "").split(" ").filter((word) => /^[a-z][a-z-]*$/.test(word));
    const words = [];
    for (const word of path) {
      if (words.join("-") === command.name) break;
      words.push(word);
    }
    const ran = await harness.behavior.runCli([...words, "--help"]);
    help.set(command.name, (ran.stdout ?? "").trimEnd());
  }
  await harness.lifecycle.dispose();
  return { cli: registrations.cli, tools: [...registrations.agentTools].sort((a, b) => a.name.localeCompare(b.name)), help };
}

function cliPage(found: Registered): string {
  const commands = found.cli.commands;
  const name = (command: { usage: string }) => command.usage.split(/ [<[]/)[0]!;
  const lines = [
    "# CLI reference",
    "",
    `\`bb box\`: ${found.cli.summary} Each command's \`--help\` prints what is below.`,
    "",
    table(["Command", "What it does"], commands.map((command) => [`[\`${name(command)}\`](#${anchor(name(command))})`, command.summary])),
  ];
  for (const command of commands) {
    const help = found.help.get(command.name) ?? "";
    // The first line repeats the command and its summary.
    const body = help.split("\n").slice(1).join("\n").replace(/^\n+/, "");
    lines.push("", `## ${name(command)}`, "", command.summary, "", "```text", body, "```");
  }
  return `${HEADER}${lines.join("\n")}\n`;
}

/** A JSON schema's type, in a word or two. */
function typeOf(schema: JsonSchema): string {
  if (schema.enum) return schema.enum.map((value) => `\`${String(value)}\``).join(", ");
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(" or ");
  const type = typeof schema.type === "string" ? schema.type : schema.type ? schema.type.join(" or ") : "any";
  return type === "array" && schema.items ? `array of ${typeOf(schema.items)}` : type;
}

function toolsPage(found: Registered): string {
  const lines = [
    "# Agent tools",
    "",
    "The tools bb-box gives a thread's agent, with their parameters as the agent sees them.",
    "",
    table(["Tool", "What it does"], found.tools.map((tool) => [`[\`${tool.name}\`](#${anchor(tool.name)})`, tool.description.split(/(?<=\.)\s/)[0]])),
  ];
  for (const tool of found.tools) {
    lines.push("", `## ${tool.name}`, "", tool.description);
    const properties = Object.entries(tool.inputSchema.properties ?? {});
    const required = new Set(tool.inputSchema.required ?? []);
    lines.push("", properties.length ? table(["Parameter", "Type", "Required", "Description"], properties.map(([key, schema]) => [`\`${key}\``, typeOf(schema), required.has(key) ? "yes" : "no", schema.description ?? ""])) : "It takes no parameters.");
  }
  return `${HEADER}${lines.join("\n")}\n`;
}

/** The members of an interface in src/core/document.ts, with their doc comments, as the code says them. */
function members(source: ts.SourceFile, name: string): { key: string; optional: boolean; type: string; doc: string }[] {
  const found: { key: string; optional: boolean; type: string; doc: string }[] = [];
  source.forEachChild((node) => {
    if (!ts.isInterfaceDeclaration(node) || node.name.text !== name) return;
    for (const member of node.members) {
      if (!ts.isPropertySignature(member) || !member.name) continue;
      const doc = ts
        .getJSDocCommentsAndTags(member)
        .map((comment) => (typeof comment.comment === "string" ? comment.comment : ""))
        .join(" ")
        .trim();
      found.push({ key: member.name.getText(source), optional: !!member.questionToken, type: member.type?.getText(source).replace(/\s+/g, " ") ?? "", doc });
    }
  });
  if (!found.length) throw new Error(`No interface ${name} in src/core/document.ts.`);
  return found;
}

function defaultOf(field: FieldDescriptor): string {
  const value = (field as { default?: unknown }).default;
  if (value === undefined || value === "") return "";
  return `\`${String(value)}\``;
}

function fieldRows(fields: Readonly<Record<string, FieldDescriptor>>): unknown[][] {
  return Object.entries(fields).map(([key, field]) => [
    `\`${key}\``,
    field.label,
    `${field.type}${(field as { secret?: boolean }).secret ? ", secret" : ""}`,
    field.group,
    defaultOf(field),
    field.description ?? "",
  ]);
}

