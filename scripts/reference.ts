/** Every page, by file name, as the code says it now. */
export async function referencePages(): Promise<Record<string, string>> {
  const found = await registered();
  return {
    "README.md": indexPage(),
    "cli.md": cliPage(found),
    "tools.md": toolsPage(found),
    "configuration.md": configurationPage(),
    "kinds.md": kindsPage(),
    "checks.md": checksPage(),
    "files.md": filesPage(),
  };
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("reference.ts")) {
  const pages = await referencePages();
  if (process.argv.includes("--check")) {
    const stale = Object.entries(pages).filter(([file, text]) => {
      try {
        return readFileSync(join(REFERENCE_DIR, file), "utf8") !== text;
      } catch {
        return true;
      }
    });
    for (const [file] of stale) console.error(`docs/reference/${file} is out of date: run npm run reference.`);
    process.exit(stale.length ? 1 : 0);
  }
  mkdirSync(REFERENCE_DIR, { recursive: true });
  for (const [file, text] of Object.entries(pages)) writeFileSync(join(REFERENCE_DIR, file), text);
  console.log(`Wrote ${Object.keys(pages).length} pages in docs/reference.`);
  process.exit(0);
}
