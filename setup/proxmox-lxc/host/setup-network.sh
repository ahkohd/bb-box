#!/bin/bash
# Sets up bb-box's box network on a Proxmox host: a bridge with no physical
# port, IPv4 forwarding, an nft table that masquerades the boxes' subnet out
# of every other interface, and a unit and timer that load the table at boot
# and restore the bridge or table if they go missing. It filters nothing:
# boxes reach what the host reaches, and whatever routes to the subnet through
# the host reaches the boxes.
#
# Idempotent. Settings: /etc/bb-box/bb-box.env (see bb-box.env.example).
# usage: setup-network.sh
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=common.sh
. "$here/common.sh"

subnet=$(bbbox_subnet)
stamp=$(date -u +%Y%m%dT%H%M%S%NZ)
install -d -m 0755 /etc/bb-box
install -d -m 0700 /root/bb-box /root/bb-box/backup

# 1. The bridge, in /etc/network/interfaces itself: Proxmox's network API
#    reads only that file, not interfaces.d.
if grep -qE "^(auto|iface) $BBBOX_BRIDGE( |\$)" /etc/network/interfaces; then
  stanza=$(awk -v b="$BBBOX_BRIDGE" '$1 == "iface" && $2 == b { p = 1; print; next } p && /^[^ \t]/ { p = 0 } p' /etc/network/interfaces)
  grep -q "inet static" <<<"$stanza" && grep -q "address $BBBOX_GATEWAY_CIDR" <<<"$stanza" &&
    grep -q "bridge-ports none" <<<"$stanza" ||
    die "/etc/network/interfaces already has a different $BBBOX_BRIDGE; refusing to change it"
  echo "$BBBOX_BRIDGE is already defined"
else
  ip link show "$BBBOX_BRIDGE" >/dev/null 2>&1 && die "$BBBOX_BRIDGE exists but is not in /etc/network/interfaces"
  cp -a /etc/network/interfaces "/root/bb-box/backup/interfaces.$stamp"
  cat >>/etc/network/interfaces <<EOF

# bb-box boxes: a bridge with no physical port. The host routes and
# masquerades it (nft table ip bbbox, /etc/bb-box/network.nft).
auto $BBBOX_BRIDGE
iface $BBBOX_BRIDGE inet static
	address $BBBOX_GATEWAY_CIDR
	bridge-ports none
	bridge-stp off
	bridge-fd 0
EOF
  echo "added $BBBOX_BRIDGE to /etc/network/interfaces (backup: /root/bb-box/backup/interfaces.$stamp)"
fi

# 2. Forwarding.
printf 'net.ipv4.ip_forward = 1\n' >/etc/sysctl.d/90-bb-box.conf
sysctl -q -p /etc/sysctl.d/90-bb-box.conf

# 3. The NAT table. The first two lines make every load atomic and idempotent.
{
  echo "#!/usr/sbin/nft -f"
  echo "# bb-box box network: generated by setup-network.sh from /etc/bb-box/bb-box.env."
  echo "table ip bbbox"
  echo "delete table ip bbbox"
  echo "table ip bbbox {"
  echo "	chain prerouting {"
  echo "		type nat hook prerouting priority dstnat; policy accept;"
  for rule in $BBBOX_DNAT; do
    [[ "$rule" =~ ^([0-9.]+):([0-9]+)=([0-9.]+)(:([0-9]+))?$ ]] || die "BBBOX_DNAT: cannot read '$rule' (ADDRESS:PORT=TARGET[:PORT])"
    to=${BASH_REMATCH[3]}
    [ -z "${BASH_REMATCH[5]}" ] || to="$to:${BASH_REMATCH[5]}"
    echo "		iifname \"$BBBOX_BRIDGE\" ip daddr ${BASH_REMATCH[1]} tcp dport ${BASH_REMATCH[2]} dnat to $to"
  done
  echo "	}"
  echo "	chain forward {"
  echo "		type filter hook forward priority filter; policy accept;"
  echo "		# Fit TCP to each route's MTU, for example a VPN's 1280."
  echo "		iifname \"$BBBOX_BRIDGE\" tcp flags syn tcp option maxseg size set rt mtu"
  echo "		oifname \"$BBBOX_BRIDGE\" tcp flags syn tcp option maxseg size set rt mtu"
  echo "	}"
  echo "	chain postrouting {"
  echo "		type nat hook postrouting priority srcnat; policy accept;"
  echo "		ip saddr $subnet oifname != \"$BBBOX_BRIDGE\" masquerade"
  echo "	}"
  echo "}"
} >/etc/bb-box/network.nft.new
nft -c -f /etc/bb-box/network.nft.new
mv /etc/bb-box/network.nft.new /etc/bb-box/network.nft
cat >/etc/bb-box/network.env <<EOF
# Read by bb-box-network. Generated by setup-network.sh.
BBBOX_BRIDGE=$BBBOX_BRIDGE
BBBOX_GATEWAY_CIDR=$BBBOX_GATEWAY_CIDR
BBBOX_SUBNET=$subnet
EOF
install -m 0755 "$here/bb-box-network" /usr/local/sbin/bb-box-network

cat >/etc/systemd/system/bb-box-network.service <<'EOF'
[Unit]
Description=bb-box box network: bring up the bridge and its NAT table if missing
After=networking.service

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/bb-box-network repair

[Install]
WantedBy=multi-user.target
EOF
cat >/etc/systemd/system/bb-box-network.timer <<'EOF'
[Unit]
Description=Restore the bb-box box network every 30 s if any part is missing

[Timer]
OnBootSec=30s
OnUnitActiveSec=30s
AccuracySec=1s

[Install]
WantedBy=timers.target
EOF
systemctl daemon-reload

# 4. Up now. Loading the table replaces any older version atomically.
ifup "$BBBOX_BRIDGE"
nft -f /etc/bb-box/network.nft
systemctl enable --quiet bb-box-network.service bb-box-network.timer
systemctl start bb-box-network.timer
/usr/local/sbin/bb-box-network check
echo "bb-box network ready: $BBBOX_BRIDGE $BBBOX_GATEWAY_CIDR, boxes masqueraded out of every other interface"
